def test_a_claimed_position_the_1996_edition_lacks_is_reported_as_unknown(rules, settings):
    """Test Case A, end to end. Refused, named, and kept out of the money — not silently dropped."""
    report = audit(INVOICE_5_AND_20, OLDEST, rules, settings)

    twenty = row(report, "20")
    assert twenty.verdict == "unknown_ziffer"
    assert twenty.in_catalog is False
    assert twenty.recomputed_amount_eur is None
    assert "1996" in twenty.reason or "goae_1996" in twenty.reason, (
        "the reason must name the catalog that lacks it, so the reader knows it is a temporal "
        f"verdict and not a typo: {twenty.reason!r}"
    )
    assert any(f.type == "padnext_unknown_ziffer" and f.ziffer == "20" for f in report.findings)

    # Its claimed euros are unpriceable, not defensible, and not silently absent from the totals.
    assert twenty.claimed_amount_eur == Decimal("24.13")
    assert report.unpriceable_claimed_eur == Decimal("24.13")
    assert report.recomputed_total_eur == row(report, "5").recomputed_amount_eur


def test_the_same_position_is_accepted_and_priced_under_the_current_edition(rules, settings):
    """Test Case B, end to end: same bytes, routed to 2026."""
    report = audit(INVOICE_5_AND_20, CURRENT, rules, settings)

    twenty = row(report, "20")
    assert twenty.verdict == "chargeable"
    assert twenty.in_catalog is True
    assert twenty.recomputed_amount_eur is not None and twenty.recomputed_amount_eur > 0
    assert twenty.punkte == load_catalog(catalog_version=CURRENT).get("20").punkte
    assert report.unpriceable_claimed_eur == Decimal("0.00")
    assert not any(f.type == "padnext_unknown_ziffer" for f in report.findings)


def test_one_invoice_is_worth_different_money_in_different_editions(rules, settings):
    """The reason routing exists at all: Ziffer 5 alone recomputes to three different amounts."""
    amounts = {
        version: audit(INVOICE_5_ONLY, version, rules, settings).recomputed_total_eur
        for version in ERAS
    }

    assert amounts[OLDEST] < amounts["goae_2012"] < amounts[CURRENT]
    assert amounts[CURRENT] == amounts[DRAFT]
    assert amounts[OLDEST] == Decimal("13.41"), "100 Punkte × 2.3 × 5.82873 ct, rounded half up"
    assert amounts[CURRENT] == Decimal("20.11"), "150 Punkte × 2.3 × 5.82873 ct"


