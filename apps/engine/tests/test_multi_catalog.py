def test_the_default_edition_is_the_official_snapshot():
    """The fixtures live beside the real catalog, so "which one is the default" is load-bearing.

    A fixture becoming the process default would replace the fee schedule the engine bills with,
    and every other test in the suite would still pass.
    """
    catalog = load_catalog()

    assert DEFAULT_CATALOG_VERSION == "goae_current"
    assert catalog.routed_version == "goae_current"
    assert not catalog.is_synthetic
    assert len(catalog.ziffern) >= 2000


def test_every_era_fixture_is_present_and_admits_that_it_is_a_fixture():
    available = available_catalog_versions()

    assert set(ERAS) <= set(available), f"missing era fixtures: {sorted(set(ERAS) - set(available))}"
    for version in ERAS:
        catalog = load_catalog(catalog_version=version)
        assert catalog.is_synthetic, f"{version} must declare itself synthetic"
        assert "SYNTHETIC" in catalog.source.legal_status
        assert all(z.provenance == "illustrative" for z in catalog.ziffern.values())


@pytest.mark.parametrize("version", sorted(ERAS))
def test_an_edition_resolves_to_its_own_directory(version):
    """Routing in full: the edition name is the directory name, and the overrides file that is
    applied comes from the same directory — never from another era's."""
    directory = resolve_catalog_dir(version)
    catalog_path, overrides_path = catalog_files(version)

    assert directory.name == version
    assert directory.parent.name == "catalogs"
    assert catalog_path == directory / CATALOG_FILENAME
    assert overrides_path.parent == directory
    assert load_catalog(catalog_version=version).path == catalog_path


@pytest.mark.parametrize("version,spec", sorted(ERAS.items()))
def test_the_eras_differ_exactly_where_they_are_meant_to(catalogs, version, spec):
    catalog = catalogs[version]

    assert catalog.get("5").punkte == spec["ziffer_5_punkte"], "Ziffer 5 carries the era's rate"
    assert catalog.has("20") is spec["has_20"], "Ziffer 20 is the temporal existence test"
    for novel in ("99", "999"):
        assert catalog.has(novel) is (novel == spec["novel"]), (
            f"{novel} may only exist in the edition that introduced it"
        )
    # Structurally identical: an era differs in its positions, never in its § 5 bands or Punktwert.
    assert catalog.punktwert_cent == Decimal("5.82873")
    assert catalog.factor_band("5").max == Decimal("3.5")


def test_ziffer_5_gets_dearer_with_every_edition(catalogs):
    """The "base rate" progression, read as money: 100 → 125 → 150 Punkte at the Einfachsatz."""
    einfachsatz = {
        version: catalog.get("5").punkte * catalog.punktwert_cent / 100
        for version, catalog in catalogs.items()
    }

    assert einfachsatz["goae_1996"] < einfachsatz["goae_2012"] < einfachsatz[CURRENT]
    assert einfachsatz[CURRENT] == einfachsatz[DRAFT], "the draft only renumbers a position"


