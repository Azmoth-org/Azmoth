#: The temporal differences the fixtures exist to prove, as data rather than as prose. Punkte on
#: Ziffer 5 is the "base rate" the multi-catalog brief varies: money here is
#: `Punkte × Punktwert × Faktor` (§ 5 Abs. 1 GOÄ), so a GOÄ catalog has no euro column to move.
ERAS = {
    "goae_1996": {"ziffer_5_punkte": 100, "has_20": False, "novel": None},
    "goae_2012": {"ziffer_5_punkte": 125, "has_20": True, "novel": None},
    "goae_2026_current": {"ziffer_5_punkte": 150, "has_20": True, "novel": "99"},
    "goae_neu_draft": {"ziffer_5_punkte": 150, "has_20": True, "novel": "999"},
}

OLDEST = "goae_1996"
CURRENT = "goae_2026_current"
DRAFT = "goae_neu_draft"


@pytest.fixture(scope="module")
def catalogs() -> dict:
    """Every era fixture, loaded once. `load_catalog` is cached per edition, so this is cheap."""
    return {version: load_catalog(catalog_version=version) for version in ERAS}


# ------------------------------------------------------------------------------------------
# a synthetic PADnext delivery, built here so the era under test decides the outcome
# ------------------------------------------------------------------------------------------

#: One position per line: (positionsnr, ziffer, faktor, gesamtbetrag). `gesamtbetrag` is what the
#: file *claims*; the audit recomputes it from whichever catalog it was handed, which is the point.
POSITION = '''    <goziffer positionsnr="{nr}" go="GOÄ" ziffer="{ziffer}">
      <datum>2019-03-11</datum>
      <anzahl>1</anzahl>
      <text>Synthetische Position {ziffer}</text>
      <faktor>{faktor}</faktor>
      <gesamtbetrag>{betrag}</gesamtbetrag>
    </goziffer>'''


def padnext_xml(*positions: tuple[str, str, str, str]) -> bytes:
    """A bare `*_padx.xml` payload — what `read_delivery` accepts without a container.

    Hand-written and minimal on purpose: a subset of the PADneXt 2.12 shape with no patient
    identity in it at all, because none is parsed and none should exist in a fixture.
    """
    body = "\n".join(
        POSITION.format(nr=nr, ziffer=ziffer, faktor=faktor, betrag=betrag)
        for nr, ziffer, faktor, betrag in positions
    )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- SYNTHETIC. No real patient, no real practice, no real invoice. -->
<rechnungen anzahl="1" xmlns="http://padinfo.de/ns/pad">
  <nachrichtentyp version="02.12">ADL</nachrichtentyp>
  <rechnungsersteller><name>Musterpraxis (synthetisch)</name></rechnungsersteller>
  <rechnung id="SYNTH-TEMPORAL-0001" aisrechnungsnr="RG-TEMPORAL-1">
    <abrechnungsfall>
      <behandlungsart>0</behandlungsart>
      <vertragsart>1</vertragsart>
      <positionen posanzahl="{len(positions)}">
{body}
      </positionen>
    </abrechnungsfall>
  </rechnung>
</rechnungen>
""".encode("utf-8")


#: An invoice from 2019 charging a consultation (5) and a group session (20). Ziffer 20 is the
#: temporal variable: it exists in 2012 and later, and not in 1996.
INVOICE_5_AND_20 = padnext_xml(("1", "5", "2.3", "20.11"), ("2", "20", "2.3", "24.13"))

#: Only positions every era shares, for the tests that must isolate catalog *identity* from any
#: difference in the answer.
INVOICE_5_ONLY = padnext_xml(("1", "5", "2.3", "20.11"))


def confirm_everything(extraction, bridge, proposed_factors=None) -> RulesResult:
    """A `souffle_run` stand-in that confirms every candidate it is given.

    Deliberately maximally permissive: with the rules stage confirming everything, any position
    the audit still refuses was refused by the catalog. Note that it cannot confirm what it is
    never handed — `build_audit_input` proposes every claimed GOÄ position regardless of the
    catalog, so Ziffer 20 *is* offered here even under 1996.
    """
    proposed = list(bridge.candidates)
    return RulesResult(proposed=proposed, billable=[c.ziffer for c in proposed])


def audit(body: bytes, catalog_version: str, rules, settings):
    """Read the delivery and audit it against one edition."""
    delivery, read_findings = read_delivery(body, source_name=f"{catalog_version}.xml")
    return audit_delivery(
        delivery,
        catalog=load_catalog(catalog_version=catalog_version),
        rules=rules,
        souffle_run=confirm_everything,
        read_findings=read_findings,
        settings=settings,
    )


def row(report, ziffer: str):
    return next(p for p in report.positions if p.ziffer == ziffer)


