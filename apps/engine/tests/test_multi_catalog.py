# 5. Test Case C — the receipt hash separates the editions
# ==========================================================================================


def test_the_same_invoice_audited_under_two_editions_has_two_receipts(rules, settings):
    """Test Case C. Byte-identical input, and the receipts must not collide: a receipt that did
    would claim one audit answers for both fee schedules."""
    old = audit(INVOICE_5_AND_20, OLDEST, rules, settings)
    current = audit(INVOICE_5_AND_20, CURRENT, rules, settings)

    assert old.receipt_hash != current.receipt_hash
    assert old.catalog_version != current.catalog_version
    assert old.catalog_sha256 != current.catalog_sha256


def test_the_receipt_moves_even_when_the_two_editions_agree_on_every_number(rules, settings):
    """The sharper half of Test Case C.

    2026 and the draft price Ziffer 5 identically, so this invoice audits to exactly the same
    verdict and the same cent under both. The receipts still differ — because the receipt covers
    *which* catalog answered, not only what it answered. Without that, a practice could not tell an
    audit run against the draft from one run against the edition in force.
    """
    current = audit(INVOICE_5_ONLY, CURRENT, rules, settings)
    draft = audit(INVOICE_5_ONLY, DRAFT, rules, settings)

    assert current.recomputed_total_eur == draft.recomputed_total_eur
    assert [p.model_dump() for p in current.positions] == [p.model_dump() for p in draft.positions]
    assert current.receipt_hash != draft.receipt_hash


def test_re_auditing_one_invoice_against_one_edition_is_stable(rules, settings):
    """The other direction, and the reason the test above proves anything: nothing measured — no
    timing, no timestamp — is in the hash, so a difference can only come from the inputs."""
    first = audit(INVOICE_5_AND_20, CURRENT, rules, settings)
    second = audit(INVOICE_5_AND_20, CURRENT, rules, settings)

    assert first.receipt_hash == second.receipt_hash


def test_no_two_shipped_editions_share_an_identity():
    """What makes the receipt guarantee hold for editions this test file has never heard of.

    The receipt covers the *declared* version and the file digest, not the directory name. Two
    editions that agreed on both would produce one receipt hash for two different fee schedules —
    so a new edition copied from an old one without editing its `catalog_version` fails here.
    """
    catalogs = [load_catalog(catalog_version=v) for v in available_catalog_versions()]

    declared = [c.catalog_version for c in catalogs]
    digests = [c.sha256() for c in catalogs]

    assert len(set(declared)) == len(catalogs), f"duplicate catalog_version among {declared}"
    assert len(set(digests)) == len(catalogs), "two editions are byte-identical"
    assert all(c.catalog_version and c.catalog_version != "unknown" for c in catalogs)


def test_an_edition_records_both_where_we_looked_and_what_we_found(catalogs):
    """`routed_version` is the directory; `catalog_version` is the file's own claim. Keeping both
    is what makes a mislabelled edition directory detectable at all."""
    for version, catalog in catalogs.items():
        assert catalog.routed_version == version
        assert catalog.catalog_version != version, "the two are different claims, not aliases"
        assert version.removeprefix("goae_").split("_")[0] in catalog.catalog_version


