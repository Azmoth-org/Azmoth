def test_the_committed_fixtures_match_their_generator():
    """Four catalogs that must stay structurally identical are not something to edit by hand. If
    this fails, run `python scripts/make_temporal_fixtures.py`."""
    spec = importlib.util.spec_from_file_location(
        "make_temporal_fixtures", ENGINE_DIR / "scripts" / "make_temporal_fixtures.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    assert module.build(check=True) == 0
