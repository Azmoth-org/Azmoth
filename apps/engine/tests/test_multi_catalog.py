# ==========================================================================================
# 3. Test Cases A and B — the solver can only bill what the routed edition contains
# ==========================================================================================
#
# Two facts about this layer decide how these tests are written, and both are pre-existing
# engine behaviour rather than anything routing introduced:
#
#   * `app/bridge/entity_to_ziffer.py` holds a hard invariant — never propose a Ziffer the loaded
#     catalog does not contain — so a position outside the routed edition is dropped, with an
#     `unknown_ziffer` warning, before Soufflé or Clingo ever see it.
#   * `logic/asp/goae_optimize.lp:87` (`:- charged(Z), not code_info(Z, _, _).`) makes charging an
#     unknown position unsatisfiable rather than silently dropping it, described in that file as
#     belt and braces for exactly the injection this file is about.
#
# So the solver-level question is not "does Clingo reject Ziffer 20 in 1996" — it is "does the
# routed edition decide what Clingo is even told about", which is what `build_facts` answers.


def solver_for(version: str, settings, rules) -> ClingoSolver:
    return ClingoSolver(settings, load_catalog(catalog_version=version), rules)


def facts_for(version: str, *ziffern: str, settings, rules) -> str:
    """The injected Clingo facts for a set of confirmed positions, under one edition."""
    bridge = one_act_per_ziffer(*ziffern)
    rules_result = RulesResult(proposed=list(bridge.candidates), billable=list(ziffern))
    return solver_for(version, settings, rules).build_facts(
        rules_result, make_extraction(), bridge
    )


def solve_under(version: str, *ziffern: str, settings, rules):
    bridge = one_act_per_ziffer(*ziffern)
    rules_result = RulesResult(proposed=list(bridge.candidates), billable=list(ziffern))
    return solver_for(version, settings, rules).solve(
        rules_result, make_extraction(), bridge
    )


def test_the_routed_edition_decides_what_the_solver_is_told(settings, rules):
    """Test Case A at the solver boundary: the 1996 edition emits no catalog fact for Ziffer 20,
    so there is nothing for the ASP program to charge. An absent position is not a suppressed
    one — no rule fires, and none should."""
    old = facts_for(OLDEST, "5", "20", settings=settings, rules=rules)
    current = facts_for(CURRENT, "5", "20", settings=settings, rules=rules)

    assert 'code_info("20"' not in old
    assert 'code_info("5", 100,' in old, "Ziffer 5 at the 1996 rate"

    assert 'code_info("20"' in current
    assert 'code_info("5", 150,' in current, "and at the 2026 rate under the 2026 edition"


def test_the_novel_position_only_reaches_the_solver_from_the_edition_that_declares_it(
    settings, rules
):
    """99 exists in 2026 and 999 in the draft, so a position that is priced at all identifies the
    edition that priced it."""
    current = facts_for(CURRENT, "99", settings=settings, rules=rules)
    draft = facts_for(DRAFT, "99", settings=settings, rules=rules)

    assert 'code_info("99"' in current
    assert 'code_info("99"' not in draft
    assert 'code_info("999"' in facts_for(DRAFT, "999", settings=settings, rules=rules)
    assert 'code_info("999"' not in facts_for(CURRENT, "999", settings=settings, rules=rules)


def test_the_solver_bills_and_prices_ziffer_20_under_the_current_edition(settings, rules):
    """Test Case B. Both positions are in the 2026 edition, so both are charged and both get a
    § 5 factor decision — and the money is that edition's."""
    catalog = load_catalog(catalog_version=CURRENT)
    result = solve_under(CURRENT, "5", "20", settings=settings, rules=rules)

    assert result.solver_status == "SAT"
    assert {"5", "20"} <= set(result.billed)
    assert result.factor_for("20") is not None
    assert result.total_punkte == catalog.get("5").punkte + catalog.get("20").punkte


def test_the_same_position_is_priced_at_each_editions_rate(settings, rules):
    """Ziffer 5 alone through the real solver, so the only thing that can move the money is which
    catalog was routed to."""
    punkte = {
        version: solve_under(version, "5", settings=settings, rules=rules).total_punkte
        for version in ERAS
    }

    assert punkte == {v: spec["ziffer_5_punkte"] for v, spec in ERAS.items()}


def test_routing_has_to_happen_before_the_solver_not_inside_it(settings, rules):
    """Handing Clingo a confirmed position the routed edition does not contain is an error, and
    pinning that is the point: it is why the guard lives upstream.

    `logic/asp/goae_optimize.lp:87` refuses to charge a position with no catalog fact, so an
    injection that claimed Ziffer 20 is billable under 1996 is unsatisfiable rather than quietly
    reduced. Nothing in the engine produces that input — the bridge drops unknown Ziffern and the
    PADnext audit never reaches Clingo — but a future caller that routes an era *after* candidate
    selection would land here, and a loud failure is the right outcome.
    """
    with pytest.raises(ClingoError):
        solve_under(OLDEST, "5", "20", settings=settings, rules=rules)


