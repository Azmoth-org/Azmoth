"""Temporal catalog routing: auditing an invoice against the fee schedule it was written under.

A GOÄ position is not a constant. Ziffer 20 did not exist in 1996, and Ziffer 5 has been worth
different Punktzahlen in different editions — so an invoice from one era priced against another
era's catalog produces exact arithmetic on the wrong law. `data/catalogs/` therefore holds one
directory per edition and `load_catalog(catalog_version=...)` chooses one.

These tests are what make the routing claim falsifiable. Three layers, and they fail for different
reasons on purpose:

    routing     the right directory is opened, and an unknown edition is refused rather than
                quietly served from the default
    solving     Clingo cannot bill a position the routed edition does not contain, and prices the
                positions it does contain at that edition's Punktzahl
    identity    the same bytes audited under two editions produce two receipt hashes — including
                when the two editions agree on every number, because the receipt covers *which*
                catalog answered, not only what it said

`goae_current` is the real official snapshot; the four era directories are synthetic fixtures
generated by `scripts/make_temporal_fixtures.py` (see `data/catalogs/README.md`). Only the
fixtures are asserted on here — the official snapshot has its own identity suite in
`tests/test_catalog_snapshot_identity.py`, and pinning fixture Punktzahlen there would be claiming
they mean something.

Nothing here needs the Soufflé binary: `audit_delivery` takes `souffle_run` as an argument, so the
rules stage is stubbed to confirm everything it is handed. That is deliberate rather than
convenient — a stub that confirms every position means a position that is *not* charged was
dropped by the catalog, which is exactly the variable under test.
"""

